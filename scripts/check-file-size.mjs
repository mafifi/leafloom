import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const skipped = new Set([
  'node_modules',
  '.git',
  'dist',
  'build',
  'target',
  'coverage',
  'reference',
  'binaries',
]);
const source = /\.(?:ts|tsx|js|mjs|cjs|svelte|rs|css)$/;
export const FAIL_AT = 1000;
// Temporary debt is frozen while the approved responsibility-based extraction proceeds.
export const ALLOWLIST = {};
export const lineCount = (text) =>
  text ? text.split('\n').length - Number(text.endsWith('\n')) : 0;
export function checkSizes(files, list = ALLOWLIST) {
  const violations = [],
    warnings = [];
  for (const [filename, lines] of files) {
    const allowed = list[filename];
    if (allowed) {
      if (lines < FAIL_AT) violations.push(`${filename}: remove completed size exception`);
      else if (lines > allowed.lines)
        violations.push(
          `${filename}: ${lines} lines exceeds frozen ${allowed.lines}; ${allowed.task}`,
        );
    } else if (lines >= FAIL_AT)
      violations.push(
        `${filename}: ${lines} lines; split by responsibility (limit ${FAIL_AT - 1})`,
      );
    else if (lines > (path.basename(filename) === 'content.ts' ? 300 : 400))
      warnings.push({ path: filename, lines });
  }
  for (const filename of Object.keys(list))
    if (!files.has(filename)) violations.push(`${filename}: remove missing size exception`);
  return { violations, warnings };
}
export function sourceSizes(directory = root) {
  const sizes = new Map();
  function walk(folder) {
    for (const entry of readdirSync(folder, { withFileTypes: true })) {
      if (skipped.has(entry.name) || entry.name.startsWith('.')) continue;
      const filename = path.join(folder, entry.name);
      if (entry.isDirectory()) walk(filename);
      else if (source.test(filename) && !filename.endsWith('.d.ts')) {
        const text = readFileSync(filename, 'utf8');
        if (/^\/\/ Generated by|@generated/.test(text.split('\n', 1)[0])) continue;
        sizes.set(path.relative(directory, filename).split(path.sep).join('/'), lineCount(text));
      }
    }
  }
  for (const folder of ['apps', 'packages', 'scripts', 'tests']) walk(path.join(directory, folder));
  return sizes;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const report = checkSizes(sourceSizes());
  for (const warning of report.warnings)
    console.warn(`Size warning: ${warning.path} (${warning.lines} lines)`);
  for (const violation of report.violations) console.error(violation);
  if (report.violations.length) process.exitCode = 1;
  else
    console.log(
      `Source size policy passed; ${Object.keys(ALLOWLIST).length} frozen extraction tasks.`,
    );
}
